#!/usr/bin/env python3
"""Measures a recorded test tone for hardware A/B comparisons (SPEC §15.4).

    python3 tools/capture/analyse.py RECORDING.wav [--from S] [--to S]

Reports, for the chosen time window: the decay/attack slope of the RMS
envelope in dB/s (compare with R-E4 / AC-E4.1), the fundamental frequency by
zero crossings (R-E6), and the period of any slow amplitude/pitch modulation
(LFO, R-E7). Record the instrument and VDX with the same test voice (see
README.md) and compare the two reports; measured differences are what the
engine tables in core/fm/ (generated by tools/gen_tables.py, or the constants
in core/fm/dx7tables.h) are adjusted from.
Pure Python (wave module), mono or stereo, 16/24/32-bit PCM.
"""
import math
import struct
import sys
import wave


def read(path):
    with wave.open(path, "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    full = float(1 << (8 * width - 1))
    out = []
    for i in range(n):
        o = i * ch * width
        b = raw[o:o + width]
        if width == 2:
            v = struct.unpack("<h", b)[0]
        elif width == 3:
            v = int.from_bytes(b, "little", signed=True)
        else:
            v = struct.unpack("<i", b)[0]
        out.append(v / full)
    return out, rate


def envelope_db(x, rate, win_s=0.01, freq=0.0):
    # whole periods of the tone per window, so the RMS has no window ripple
    w = max(1, int(rate * win_s))
    if freq > 0:
        period = rate / freq
        w = max(1, int(round(max(1, round(win_s * freq)) * period)))
    env = []
    for i in range(0, len(x) - w, w):
        s = sum(v * v for v in x[i:i + w]) / w
        env.append(10 * math.log10(s + 1e-30))
    return env, w / rate


def slope(env, dt):
    n = len(env)
    if n < 3:
        return 0.0
    t = [i * dt for i in range(n)]
    mt, me = sum(t) / n, sum(env) / n
    num = sum((a - mt) * (b - me) for a, b in zip(t, env))
    den = sum((a - mt) ** 2 for a in t)
    return num / den if den else 0.0


def zero_cross_freq(x, rate):
    first = last = None
    count = 0
    for i in range(1, len(x)):
        if x[i - 1] < 0 <= x[i]:
            tt = i - 1 + (-x[i - 1]) / (x[i] - x[i - 1])
            if first is None:
                first = tt
            else:
                count += 1
            last = tt
    return count * rate / (last - first) if count else 0.0


def modulation_period(env, dt):
    """Period of a periodic envelope component (autocorrelation of the detrended
    dB envelope: the highest peak after the first zero crossing)."""
    n = len(env)
    k = slope(env, dt)
    m = sum(env) / n
    c = [v - m - k * (i * dt - (n - 1) * dt / 2) for i, v in enumerate(env)]
    r0 = sum(v * v for v in c)
    if r0 < 1e-3 * n:  # residual below ~0.03 dB RMS: no modulation
        return 0.0
    r = [sum(a * b for a, b in zip(c, c[lag:])) / r0 for lag in range(n // 2)]
    lag = 1
    while lag < len(r) and r[lag] > 0:
        lag += 1
    best, best_lag = 0.3, 0  # a repeat must explain at least 30 % of the residual
    for l in range(lag, len(r)):
        if r[l] > best and r[l] >= r[l - 1] and (l + 1 >= len(r) or r[l] >= r[l + 1]):
            best, best_lag = r[l], l
            break
    return best_lag * dt


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    x, rate = read(sys.argv[1])
    a = float(sys.argv[sys.argv.index("--from") + 1]) if "--from" in sys.argv else 0.0
    b = float(sys.argv[sys.argv.index("--to") + 1]) if "--to" in sys.argv else len(x) / rate
    seg = x[int(a * rate):int(b * rate)]
    f0 = zero_cross_freq(seg, rate)
    env, dt = envelope_db(seg, rate, freq=f0)
    print(f"window {a:.3f}-{b:.3f} s at {rate} Hz")
    print(f"level      {max(env):.2f} dBFS peak RMS")
    print(f"slope      {slope(env, dt):.3f} dB/s")
    print(f"frequency  {f0:.3f} Hz")
    print(f"modulation period {modulation_period(env, dt):.4f} s (0 = none)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

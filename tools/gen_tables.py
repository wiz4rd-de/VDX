#!/usr/bin/env python3
"""Generate the committed integer tables of the VDX engine (SPEC R-E3, §14).

    python3 tools/gen_tables.py          # write core/fm/tables/*.inc
    python3 tools/gen_tables.py --check  # fail if the committed tables differ

All values use round-half-up (floor(x + 0.5)), never banker's rounding.
"""
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "core" / "fm" / "tables"
INTERNAL_RATE = 49096


def rnd(x: float) -> int:
    return int(math.floor(x + 0.5))


def logsin():
    # logsin[i] = round(-1024 * log2(sin((i + 0.5) / 1024 * pi/2)))
    return [rnd(-1024.0 * math.log2(math.sin((i + 0.5) / 1024.0 * math.pi / 2.0))) for i in range(1024)]


def exptab():
    # exptab[i] = round(2^(13 - i/1024))
    return [rnd(2.0 ** (13.0 - i / 1024.0)) for i in range(1024)]


def freqlut(rate: int):
    # Phase increment (Q24 cycles/sample) for logfreq = i/1024 octave above
    # 2^20 Hz, shifted down at lookup time (MSFA freqlut convention).
    base = float(1 << 44) / rate
    return [rnd(base * 2.0 ** (i / 1024.0)) for i in range(1025)]


def finetab():
    # round(2^24 / ln 2 * ln(1 + 0.01 * fine)), fine = 0..99 (R-E6)
    return [rnd((1 << 24) / math.log(2.0) * math.log(1.0 + 0.01 * f)) for f in range(100)]


def emit(name: str, ctype: str, values, per_line=12) -> str:
    lines = [f"// Generated by tools/gen_tables.py. Do not edit.", f"// {name}[{len(values)}]"]
    for i in range(0, len(values), per_line):
        lines.append(", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines) + "\n"


def tables():
    return {
        "logsin.inc": emit("logsin", "uint16_t", logsin()),
        "exptab.inc": emit("exptab", "uint16_t", exptab()),
        "freqlut_49096.inc": emit("freqlut_49096", "int32_t", freqlut(INTERNAL_RATE), 8),
        "finetab.inc": emit("finetab", "int32_t", finetab(), 8),
    }


def main() -> int:
    check = "--check" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    bad = []
    for name, text in tables().items():
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != text:
                bad.append(name)
        else:
            path.write_text(text)
    if check:
        if bad:
            print("tables differ from generator:", ", ".join(bad))
            return 1
        print("tables up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())

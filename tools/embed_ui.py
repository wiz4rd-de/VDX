#!/usr/bin/env python3
"""Build the VDX UI with Vite and embed every file of ui/dist into a C++ source.

Used by plugin/CMakeLists.txt at build time (the desktop editor serves the UI
from memory through the WebBrowserComponent resource provider; nothing is
loaded from disk or the network at runtime).

    python3 tools/embed_ui.py --ui ui --out build/.../ui_resources.cpp [--npm npm] [--no-build]

Steps:
  1. `npm ci` when ui/node_modules is missing, then `npm run build` (-> ui/dist).
     Without Node.js / npm the build stops with a message saying so.
  2. Writes a C++ file with one byte array per file of ui/dist and a table
     path -> bytes ("/index.html", "/assets/index-abc.js", ...). The output is
     rewritten only when its content changes.
"""
import argparse
import pathlib
import shutil
import subprocess
import sys


def fail(msg: str) -> None:
    print(f"embed_ui: error: {msg}", file=sys.stderr, flush=True)
    sys.exit(1)


def find_tool(explicit, names):
    if explicit:
        p = pathlib.Path(explicit)
        if p.exists():
            return str(p)
        found = shutil.which(explicit)
        if found:
            return found
    for n in names:
        found = shutil.which(n)
        if found:
            return found
    return None


def run(cmd, cwd: pathlib.Path) -> None:
    print("embed_ui: " + " ".join(str(c) for c in cmd) + f"   (in {cwd})", flush=True)
    r = subprocess.run([str(c) for c in cmd], cwd=str(cwd))
    if r.returncode != 0:
        fail(f"'{' '.join(str(c) for c in cmd)}' failed with exit code {r.returncode}")


def build_ui(ui: pathlib.Path, npm_hint) -> None:
    npm = find_tool(npm_hint, ["npm", "npm.cmd"])
    node = find_tool(None, ["node", "node.exe"])
    if not npm or not node:
        fail("Node.js and npm are required to build the VDX user interface (ui/dist) that the plugin and "
             "standalone app embed. Install Node.js and npm, or configure with -DVDX_BUILD_PLUGIN=OFF.")
    if not (ui / "node_modules").is_dir():
        run([npm, "ci", "--no-audit", "--no-fund"], ui)
    run([npm, "run", "build"], ui)


def c_array(data: bytes) -> str:
    if not data:
        return "0"
    lines = []
    for i in range(0, len(data), 20):
        lines.append(",".join(str(b) for b in data[i:i + 20]))
    return ",\n".join(lines)


def generate(dist: pathlib.Path) -> str:
    if not (dist / "index.html").is_file():
        fail(f"{dist} has no index.html: the UI build did not produce ui/dist")
    # The WASM core (web build only, copied from ui/public when web/build.sh has
    # run) is never needed by the desktop shells: keep the embedded set the same
    # on every machine.
    web_only = {"vdx.js", "vdx.wasm", "vdx.aw.js", "vdx.worker.js"}
    files = sorted((p for p in dist.rglob("*") if p.is_file() and p.relative_to(dist).as_posix() not in web_only),
                   key=lambda p: p.relative_to(dist).as_posix())
    out = [
        "// Generated by tools/embed_ui.py from ui/dist. Do not edit.",
        '#include "ui_resources.h"',
        "",
        "namespace vdx::plugin {",
        "namespace {",
    ]
    table = []
    for i, f in enumerate(files):
        data = f.read_bytes()
        rel = "/" + f.relative_to(dist).as_posix()
        out.append(f"// {rel}")
        out.append(f"const unsigned char kFile{i}[] = {{\n{c_array(data)}}};")
        path_literal = rel.replace("\\", "\\\\").replace('"', '\\"')
        table.append(f'  {{"{path_literal}", kFile{i}, {len(data)}u}},')
    out.append("const EmbeddedFile kFiles[] = {")
    out.extend(table)
    out.append("};")
    out.append("}  // namespace")
    out.append("")
    out.append("const EmbeddedFile* embeddedFiles(std::size_t& count) {")
    out.append("  count = sizeof kFiles / sizeof kFiles[0];")
    out.append("  return kFiles;")
    out.append("}")
    out.append("")
    out.append("}  // namespace vdx::plugin")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ui", required=True, help="the ui/ directory")
    ap.add_argument("--out", required=True, help="generated .cpp")
    ap.add_argument("--npm", default=None, help="npm executable")
    ap.add_argument("--no-build", action="store_true", help="embed an existing ui/dist without building")
    args = ap.parse_args()
    ui = pathlib.Path(args.ui).resolve()
    out = pathlib.Path(args.out)
    if not args.no_build:
        build_ui(ui, args.npm)
    text = generate(ui / "dist")
    if out.exists() and out.read_text(encoding="utf-8") == text:
        print(f"embed_ui: {out} is up to date", flush=True)
    else:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"embed_ui: wrote {out}", flush=True)
    # Touch so the build system sees the output as newer than its inputs.
    out.touch()
    return 0


if __name__ == "__main__":
    sys.exit(main())

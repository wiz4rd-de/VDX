export const GLYPH_COLS = 5;
export const GLYPH_ROWS = 7;
export const CELL_ROWS = 8;
export const FIRST_CODE = 0x20;
export const LAST_CODE = 0x7e;

/**
 * Glyph for a character code as 7 row bitmasks (bit 4 = leftmost dot).
 * Codes outside 0x20–0x7E show as a space.
 */
export function glyphRows(code: number): number[] {
  const ch = code >= FIRST_CODE && code <= LAST_CODE ? String.fromCharCode(code) : ' ';
  const g = GLYPHS[ch] ?? GLYPHS[' '];
  return g.map((row) => {
    let bits = 0;
    for (let c = 0; c < GLYPH_COLS; c++) if (row[c] === '#') bits |= 1 << (GLYPH_COLS - 1 - c);
    return bits;
  });
}

/** Raw glyph table (for tests). */
export const FONT5X7: Readonly<Record<string, readonly string[]>> = GLYPHS;

/** Lit dots of a cell as [col, row] pairs; `block` lights the whole 5×8 cell (cursor). */
export function cellDots(code: number, block = false): [number, number][] {
  const dots: [number, number][] = [];
  if (block) {
    for (let r = 0; r < CELL_ROWS; r++) for (let c = 0; c < GLYPH_COLS; c++) dots.push([c, r]);
    return dots;
  }
  const rows = glyphRows(code);
  rows.forEach((bits, r) => {
    for (let c = 0; c < GLYPH_COLS; c++) if (bits & (1 << (GLYPH_COLS - 1 - c))) dots.push([c, r]);
  });
  return dots;
}
